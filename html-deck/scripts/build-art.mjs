import * as k from '../../skills/anatomy/kit/iso-kit.mjs';
import {writeFileSync} from 'node:fs';
const P=k.fitProjection([[-110,-70,0],[110,85,0],[-110,-70,190],[110,85,190]],700,640,{pad:28,azimuth:42,elevation:28});
let parts=0;
const slab=(x,y,w,d,z,h,tone='hi',lit=false)=>{parts++;return k.solidSvg(k.slabOf({x,y,w,d,r:2},z,h,P,3,.6),{tone,lit,crease:'mid'});};
const body=[];
for(const x of [-86,70])for(const y of [-49,59])body.push(slab(x,y,15,15,0,10,'lo'));
body.push(slab(-100,-63,200,150,10,13,'mid'));
body.push(slab(-97,-60,194,142,23,48,'hi',true));
body.push(slab(-100,-63,200,150,70,9,'mid'));
body.push(slab(-92,-54,184,76,79,20,'hi',true));
body.push(slab(-55,-43,110,47,99,3,'lo'));
body.push(slab(-49,-39,98,39,102,2,'hi',true));
for(let i=0;i<5;i++)body.push(k.lineSvg(k.lineOnTop([-39,-29+i*5],[18-i*5,-29+i*5],104,P),{tone:'mid',free:true}));
body.push(slab(-78,33,156,42,79,3,'hi'));
for(let row=0;row<3;row++)for(let col=0;col<4;col++)body.push(slab(-66+col*31,38+row*11,22,7,82,4,row===2?'mid':'hi'));
body.push(slab(64,36,14,35,82,5,'lo',true));
for(let i=0;i<8;i++)body.push(slab(96,-40+i*12,2,6,39,13,'lo'));
for(const x of [-86,81])for(const y of [-48,70])body.push(k.lineSvg(k.ring(x,y,2,79.2,P,12),{tone:'hi'}));
body.push(slab(-60,-59,120,7,99,5,'lo'));
let receipt=slab(-49,-57,98,2,104,82,'hi');
for(let row=0;row<7;row++){const z=115+row*9;receipt+=k.lineSvg(k.segment([-36,-54,z],[row%3===0?34:12,-54,z],P),{tone:'hi',free:true});parts++;}
body.push(`<g class="printer-paper">${receipt}</g>`);
body.push(slab(-30,84,60,2,38,18,'hi',true));
body.push(slab(101,48,5,8,28,25,'lo'));
body.push(slab(100,43,10,18,53,5,'mid'));
const svg=k.figureSvg({width:700,height:640,label:'Isometric receipt printer with a paper feed, twelve keys, screen, ventilation slots and a moving printed receipt',body});
writeFileSync('src/printer-art.js',`export const printerSvg = ${JSON.stringify(svg)};\n`);
writeFileSync('public/printer.svg',svg.replace('><g','><style>'+k.ISO_CSS+'</style><g'));
writeFileSync('src/anatomy.css',k.ISO_CSS);
console.log(`Built Anatomy Figure: ${parts} physical and printed parts`);
